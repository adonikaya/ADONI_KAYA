const PHOTO_SHAPES: Exclude<PhotoFrameShape, 'ornate'>[] = [
  'circle',
  'square',
  'rect',
  'portrait-rect',
  'oval',
  'rounded-rect',
];

const PHOTO_ASPECT_RATIOS: Record<Exclude<PhotoFrameShape, 'ornate'>, number> = {
  circle: 1,
  square: 1,
  rect: 0.75,
  'portrait-rect': 1.4,
  oval: 1.3,
  'rounded-rect': 1.1,
};

export function enhanceTemplateDesigns(templates: CardTemplate[]): CardTemplate[] {
  return templates.map((template, index) => {
    const lightPalette = index % 10 < 7 ? LIGHT_PALETTES[index % LIGHT_PALETTES.length] : null;
    const decorations = DECORATION_SETS[index % DECORATION_SETS.length];
    const hasDiyaDecorations =
      decorations.includes('diya') || decorations.includes('diya-corners');
    const photoShape = PHOTO_SHAPES[(index * 5 + 2) % PHOTO_SHAPES.length];
    const composition = COMPOSITIONS[index % COMPOSITIONS.length];

    return {
      ...template,
      theme: {
        ...template.theme,
        ...(lightPalette
          ? {
              bgType: 'gradient' as const,
              bgColor: lightPalette.background,
              secondaryColor: lightPalette.secondary,
              accentColor: lightPalette.accent,
            }
          : {}),
        motif: template.theme.motif === 'diya' && !hasDiyaDecorations
          ? decorations.length === 0 ? 'none' : 'om'
          : template.theme.motif,
        decorations: [...decorations],
        composition,
      },
      placeholders: {
        ...template.placeholders,
        header: {
          ...template.placeholders.header,
          ...(lightPalette ? { color: lightPalette.heading } : {}),
        },
        deceasedName: {
          ...template.placeholders.deceasedName,
          ...(lightPalette ? { color: lightPalette.heading } : {}),
        },
        datesBlock: {
          ...template.placeholders.datesBlock,
          ...(lightPalette ? { color: lightPalette.body } : {}),
        },
        villageBlock: {
          ...template.placeholders.villageBlock,
          ...(lightPalette ? { color: lightPalette.body } : {}),
        },
        besnaVenueBlock: template.placeholders.besnaVenueBlock
          ? {
              ...template.placeholders.besnaVenueBlock,
              ...(lightPalette ? { color: lightPalette.body } : {}),
            }
          : undefined,
        quoteBlock: {
          ...template.placeholders.quoteBlock,
          ...(lightPalette ? { color: lightPalette.body } : {}),
        },
        familyGridBlock: {
          ...template.placeholders.familyGridBlock,
          ...(lightPalette ? { color: lightPalette.body } : {}),
        },
        photo: {
          ...template.placeholders.photo,
          shape: photoShape,
          aspectRatio: PHOTO_ASPECT_RATIOS[photoShape],
          borderColor: lightPalette?.frame ?? template.placeholders.photo.borderColor,
          garlandStyle: index % 8 === 5
            ? 'none'
            : template.placeholders.photo.garlandStyle,
        },
        footerBlock: {
          ...template.placeholders.footerBlock,
          ...(lightPalette ? { color: '#FFFFFF' } : {}),
        },
      },
    };
  });
}

