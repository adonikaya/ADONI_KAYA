export function createAdditionalTemplates(templates: CardTemplate[]): CardTemplate[] {
  return ADDITIONAL_DESIGNS.map((design, index) => {
    const source = templates[index % templates.length];
    const [background, secondary, accent, frame, heading, body] = design.palette;
    const usesPhotoFrame = Boolean(design.decorationAssets?.photoFrame);
    const photo = {
      ...source.placeholders.photo,
      size: usesPhotoFrame ? 33 : 23 + (index % 4),
      shape: design.shape,
      aspectRatio: PHOTO_ASPECT_RATIOS[design.shape],
      borderColor: frame,
      borderWidth: index % 3 === 0 ? 6 : 4,
      garlandStyle: !usesPhotoFrame && index % 4 === 0 ? 'marigold' as const : 'none' as const,
    };

    return {
      ...source,
      id: design.id,
      name: design.name,
      gujaratiName: design.gujaratiName,
      category: design.category,
      tags: [design.category === 'besna' ? 'બેસણું' : 'શ્રદ્ધાંજલિ', 'નવું', design.name],
      thumbnailUrl: '',
      isPopular: false,
      isNew: true,
      isRabariStyle: design.border === 'rabari-embroidery',
      theme: {
        ...source.theme,
        bgType: 'gradient',
        bgColor: background,
        secondaryColor: secondary,
        accentColor: accent,
        borderStyle: design.border,
        motif: design.motif,
        decorations: design.decorations,
        composition: design.composition,
        ...(design.decorationAssets ? { decorationAssets: design.decorationAssets } : {}),
      },
      placeholders: {
        ...source.placeholders,
        header: { ...source.placeholders.header, color: heading, width: 84, fontSize: 32 },
        deceasedTitle: { ...source.placeholders.deceasedTitle, color: body },
        deceasedName: { ...source.placeholders.deceasedName, color: heading },
        photo,
        datesBlock: { ...source.placeholders.datesBlock, color: body },
        villageBlock: { ...source.placeholders.villageBlock, color: body },
        besnaVenueBlock: source.placeholders.besnaVenueBlock
          ? { ...source.placeholders.besnaVenueBlock, color: body }
          : undefined,
        quoteBlock: { ...source.placeholders.quoteBlock, color: body },
        familyGridBlock: { ...source.placeholders.familyGridBlock, color: body },
        footerBlock: { ...source.placeholders.footerBlock, color: '#FFFFFF' },
      },
    };
  });
}
