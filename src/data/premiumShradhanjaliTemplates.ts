export function createPremiumShradhanjaliTemplates(baseTemplates: CardTemplate[]): CardTemplate[] {
  const referenceTemplate = baseTemplates[0];
  return PREMIUM_SHRADHANJALI_DEFS.map((def) => {
    const [bgColor, secondaryColor, accentColor, frameColor, headingColor, bodyColor, footerTextColor] = def.palette;

    return {
      ...referenceTemplate,
      id: def.id,
      name: def.name,
      gujaratiName: def.gujaratiName,
      description: def.description,
      category: def.category,
      tags: def.tags,
      thumbnailUrl: '',
      isPopular: Boolean(def.isPopular),
      isNew: true,
      isRabariStyle: false,
      theme: {
        bgType: 'gradient',
        bgColor,
        secondaryColor,
        accentColor,
        ...(def.panelColor ? { panelColor: def.panelColor } : {}),
        borderStyle: def.border,
        motif: def.motif,
        decorations: [],
        composition: def.composition,
        layoutVariant: def.layoutVariant,
        artworkStyle: def.artworkStyle,
        ...(def.decorationAssets ? { decorationAssets: def.decorationAssets } : {}),
      },
      placeholders: {
        ...referenceTemplate.placeholders,
        header: {
          ...referenceTemplate.placeholders.header,
          color: headingColor,
          width: 84,
          fontSize: def.headerSize ?? 32,
        },
        deceasedTitle: {
          ...referenceTemplate.placeholders.deceasedTitle,
          color: bodyColor,
        },
        deceasedName: {
          ...referenceTemplate.placeholders.deceasedName,
          color: headingColor,
          fontSize: def.nameSize ?? referenceTemplate.placeholders.deceasedName.fontSize,
        },
        photo: {
          ...referenceTemplate.placeholders.photo,
          size: def.photoSize,
          shape: def.photoShape,
          aspectRatio: PHOTO_RATIOS[def.photoShape],
          borderColor: frameColor,
          borderWidth: def.layoutVariant === 'editorial' || def.artworkStyle === 'minimal-clean' ? 2.5 : 4,
          garlandStyle: 'none',
        },
        datesBlock: {
          ...referenceTemplate.placeholders.datesBlock,
          color: bodyColor,
        },
        villageBlock: {
          ...referenceTemplate.placeholders.villageBlock,
          color: bodyColor,
        },
        besnaVenueBlock: referenceTemplate.placeholders.besnaVenueBlock
          ? { ...referenceTemplate.placeholders.besnaVenueBlock, color: bodyColor }
          : undefined,
        quoteBlock: {
          ...referenceTemplate.placeholders.quoteBlock,
          color: bodyColor,
        },
        familyGridBlock: {
          ...referenceTemplate.placeholders.familyGridBlock,
          color: bodyColor,
        },
        footerBlock: {
          ...referenceTemplate.placeholders.footerBlock,
          color: footerTextColor,
        },
      },
    };
  });
}
